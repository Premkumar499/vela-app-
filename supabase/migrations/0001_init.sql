ALTER TABLE public.held_bills     ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_log      ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['invoice_series','products','customers','bills','bill_items','held_bills','audit_log']
  LOOP
    EXECUTE format('DROP POLICY IF EXISTS app_all_%s ON public.%I;', t, t);
    EXECUTE format(
      'CREATE POLICY app_all_%s ON public.%I FOR ALL TO authenticated USING (true) WITH CHECK (true);',
      t, t);
  END LOOP;
END;
$$;
