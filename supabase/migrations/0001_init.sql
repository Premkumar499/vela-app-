  customer_name  text          NOT NULL,
  customer_phone text          NOT NULL DEFAULT '',
  payment_type   text          NOT NULL DEFAULT 'Cash',   -- Cash | Credit | UPI | Card
  sales_type     text          NOT NULL DEFAULT 'Retail', -- Retail | Wholesale | Credit
  through        text          NOT NULL DEFAULT '',        -- salesman / agent
  area           text          NOT NULL DEFAULT '',
  price_list     text          NOT NULL DEFAULT 'Retail',
  remarks        text          NOT NULL DEFAULT '',
  subtotal       numeric(12,2) NOT NULL DEFAULT 0,
  discount_total numeric(12,2) NOT NULL DEFAULT 0,
