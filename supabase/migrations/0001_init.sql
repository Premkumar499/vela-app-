-- ============================================================================
-- INVOICE NUMBERING — atomic & concurrency-safe
-- ============================================================================
CREATE OR REPLACE FUNCTION public.next_invoice_number(p_series text)
RETURNS text LANGUAGE plpgsql AS $$
DECLARE
  v_num bigint;
  v_pad int;
BEGIN
  -- Atomic: row is locked until the transaction commits
  UPDATE public.invoice_series
     SET current_number = current_number + 1
   WHERE series_prefix = p_series
   RETURNING current_number, padding INTO v_num, v_pad;

  IF NOT FOUND THEN
    INSERT INTO public.invoice_series (series_prefix, current_number) VALUES (p_series, 1)
    RETURNING current_number, padding INTO v_num, v_pad;
  END IF;

  RETURN p_series || lpad(v_num::text, v_pad, '0');
END;
$$;

-- ============================================================================
-- CREATE BILL — one atomic transaction: number + header + lines + stock
-- ============================================================================
CREATE OR REPLACE FUNCTION public.create_bill(
  p_customer_id    bigint,
  p_customer_name  text,
  p_customer_phone text DEFAULT '',
  p_payment_type   text DEFAULT 'Cash',
  p_sales_type     text DEFAULT 'Retail',
  p_through        text DEFAULT '',
  p_area           text DEFAULT '',
  p_price_list     text DEFAULT 'Retail',
  p_remarks        text DEFAULT '',
  p_items          jsonb
) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE
  v_bill_id     uuid;
  v_bill_number text;
  v_line_no     int             := 0;
  v_subtotal    numeric(12,2)   := 0;
  v_discount    numeric(12,2)   := 0;
  v_grand_total numeric(12,2)   := 0;
  v_total_qty   numeric(12,3)   := 0;
  v_item        jsonb;
  v_product_id  bigint;
  v_qty         numeric(12,3);
  v_rate        numeric(12,2);
  v_disc_pct    numeric(5,2);
  v_gross       numeric(12,2);
  v_disc_amt    numeric(12,2);
  v_total       numeric(12,2);
BEGIN
  IF p_items IS NULL OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'Bill must contain at least one item';
  END IF;

  v_bill_number := public.next_invoice_number('INV');

  INSERT INTO public.bills (bill_number, series_prefix, customer_id, customer_name,
                            customer_phone, payment_type, sales_type, through, area,
                            price_list, remarks)
  VALUES (v_bill_number, 'INV', p_customer_id, p_customer_name, p_customer_phone,
          p_payment_type, p_sales_type, p_through, p_area, p_price_list, p_remarks)
  RETURNING id INTO v_bill_id;

  FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
  LOOP
    v_line_no    := v_line_no + 1;
    v_product_id := COALESCE((v_item->>'product_id')::bigint, 0);
    v_qty        := COALESCE((v_item->>'quantity')::numeric, 0);
    v_rate       := COALESCE((v_item->>'rate')::numeric, 0);
    v_disc_pct   := COALESCE((v_item->>'discount_percent')::numeric, 0);

    IF v_qty <= 0 OR v_rate <= 0 THEN
      RAISE EXCEPTION 'Line %: quantity and rate must be positive', v_line_no;
    END IF;

    -- Deduct stock atomically, refuse overselling
    UPDATE public.products
       SET stock = stock - v_qty
     WHERE id = v_product_id AND stock >= v_qty;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Insufficient stock for product id %', v_product_id;
    END IF;

    v_gross    := round(v_rate * v_qty, 2);
    v_disc_amt := round(v_gross * v_disc_pct / 100, 2);
    v_total    := round(v_gross - v_disc_amt, 2);

    v_subtotal    := v_subtotal + v_gross;
    v_discount    := v_discount + v_disc_amt;
    v_grand_total := v_grand_total + v_total;
    v_total_qty   := v_total_qty + v_qty;

    INSERT INTO public.bill_items (bill_id, line_no, product_id, product_name, unit,
                                   quantity, rate, discount_percent, discount_amount,
                                   gross_amount, total)
    VALUES (v_bill_id, v_line_no, v_product_id,
            COALESCE(v_item->>'product_name', ''),
            COALESCE(v_item->>'unit', 'PCS'),
            v_qty, v_rate, v_disc_pct, v_disc_amt, v_gross, v_total);
  END LOOP;

  UPDATE public.bills
     SET subtotal = v_subtotal, discount_total = v_discount,
         grand_total = v_grand_total, total_qty = v_total_qty, item_count = v_line_no
   WHERE id = v_bill_id;

  INSERT INTO public.audit_log (action, entity, entity_id, payload)
  VALUES ('CREATE', 'bill', v_bill_number, jsonb_build_object('grand_total', v_grand_total));

  RETURN (
    SELECT to_jsonb(b) ||
           jsonb_build_object('items',
             (SELECT jsonb_agg(to_jsonb(i) ORDER BY i.line_no)
                FROM public.bill_items i WHERE i.bill_id = b.id))
      FROM public.bills b WHERE b.id = v_bill_id
  );
END;
$$;

-- ============================================================================
-- VOID BILL — restore stock, keep the record for audit
-- ============================================================================
CREATE OR REPLACE FUNCTION public.void_bill(p_bill_number text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  v_id uuid;
BEGIN
  SELECT id INTO v_id FROM public.bills WHERE bill_number = p_bill_number AND status = 'active';
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Active bill % not found', p_bill_number;
  END IF;

  -- Restore stock
  UPDATE public.products p
     SET stock = p.stock + bi.quantity
    FROM public.bill_items bi
   WHERE bi.bill_id = v_id AND bi.product_id = p.id;

  UPDATE public.bills SET status = 'voided' WHERE id = v_id;

  INSERT INTO public.audit_log (action, entity, entity_id) VALUES ('VOID', 'bill', p_bill_number);
END;
$$;

-- ============================================================================
-- REPORTING VIEWS
-- ============================================================================
CREATE OR REPLACE VIEW public.v_daily_sales AS
SELECT bill_date,
       count(*)::int                                  AS bills,
       coalesce(sum(grand_total), 0)::numeric(12,2)   AS sales,
       coalesce(sum(discount_total), 0)::numeric(12,2) AS discounts,
       coalesce(sum(total_qty), 0)::numeric(12,3)      AS qty
FROM public.bills
WHERE status = 'active'
GROUP BY bill_date
ORDER BY bill_date DESC;

CREATE OR REPLACE VIEW public.v_top_products AS
SELECT bi.product_id,
       bi.product_name,
       sum(bi.quantity)::numeric(12,3) AS qty_sold,
       sum(bi.total)::numeric(12,2)    AS revenue
FROM public.bill_items bi
JOIN public.bills b ON b.id = bi.bill_id
WHERE b.status = 'active'
GROUP BY bi.product_id, bi.product_name
ORDER BY revenue DESC;

