-- Enables RLS and lets authenticated app users read/write all rows.
-- NOTE: If you call the API from the Flask backend with the SERVICE ROLE key,
--       RLS is bypassed automatically. RLS matters only when the Flutter app
--       talks to Supabase directly with the anon/user key.
-- ============================================================================
